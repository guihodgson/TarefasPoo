    Artes(String arte) {
        this.arte = arte;
    }

    public String getArte() {
        return arte;
    }

    public static void imprimir(Artes arte) {
        InputHandler.imprimirBonito(arte.getArte(), 0.8);
    }

    public void imprimirBonito(double tempo) {
        String[] linhas = arte.split("\n");

        int tam = 0;
        for (String linha : linhas) {
            tam++;
        }

        for (String linha : linhas) {
            for (int i = 0; i < linha.length(); i++) {                
                System.out.print(linha.charAt(i)); 
                InputHandler.sleep(tempo/(linha.length() * tam)); 
            }
            
            System.out.println();
            InputHandler.sleep(tempo/tam);
        }
    }
